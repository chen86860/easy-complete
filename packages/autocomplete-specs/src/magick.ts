// Options follow ImageMagick 7.1.2. Apart from -alpha-color, dropped early in 7.0,
// ImageMagick 7 releases have only added options, so the spec is not versioned.
// Value lists come from the installed magick.

const listCache: Fig.Cache = {
  strategy: "stale-while-revalidate",
  ttl: 1000 * 60 * 60,
};

// `magick -list NAME` prints one value per line
const listGenerator = (list: string): Fig.Generator => ({
  script: ["magick", "-list", list],
  cache: listCache,
  postProcess: (out) =>
    out
      .split("\n")
      .map((line) => line.trim())
      .filter(Boolean)
      .map((name) => ({ name, description: list })),
});

// Color and Pagesize print a table after a dashed rule: name, then value
const tableGenerator = (list: string): Fig.Generator => ({
  script: ["magick", "-list", list],
  cache: listCache,
  postProcess: (out) => {
    const lines = out.split("\n");
    const rule = lines.findIndex((line) => /^-{5,}/.test(line));
    return lines
      .slice(rule + 1)
      .map((line) => line.trim().split(/\s+/))
      .filter(([name]) => name)
      .map(([name, value]) => ({ name, description: value }));
  },
});

// `magick -list Resource` prints current limits, one per line: "  List length: unlimited"
const resourceGenerator: Fig.Generator = {
  script: ["magick", "-list", "Resource"],
  cache: listCache,
  postProcess: (out) =>
    out.split("\n").flatMap((line) => {
      const match = line.match(/^\s+([A-Za-z ]+): (.+)$/);
      if (!match) {
        return [];
      }
      const name = match[1]
        .split(" ")
        .map((word) => word[0].toUpperCase() + word.slice(1))
        .join("");
      return [{ name, description: `Current limit: ${match[2]}` }];
    }),
};

